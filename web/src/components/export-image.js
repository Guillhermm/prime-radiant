// The image is always drawn on the light palette, whatever the app theme: it is meant for slides,
// reports and print. Values are the light tokens of tokens.css, resolved over white (a unit test
// keeps them in step).
export const PALETTE = {
  bg: '#ffffff',
  text: '#151622',
  muted: '#454d66',
  border: '#e8e8e9',
  borderStrong: '#6b7490',
  surface2: '#f3f5fa',
  nodataBg: '#e4e8f2',
  nodataStripe: '#6b7490',
  synth: '#b83a00',
  synthText: '#ffffff',
  bins: ['#160b39', '#4f0d6c', '#85216b', '#bc3754', '#e65d2f', '#fb9606', '#f6d746'],
  binText: ['#ffffff', '#ffffff', '#ffffff', '#ffffff', '#000000', '#000000', '#000000'],
};

export const FONT = '"Fira Sans", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif';
export const MONO = '"Fira Code", ui-monospace, "SF Mono", Menlo, Consolas, monospace';

// Layout in CSS pixels; the PNG is drawn at SCALE device pixels per unit.
export const LAYOUT = { width: 1000, pad: 40, label: 56, cellH: 24, rowGap: 4, colGap: 4, radiant: 210 };
export const SCALE = 2;

/** Splits text into lines of at most `max` characters, at spaces. A longer word gets its own line. */
export const wrap = (text, max) => {
  const lines = [];
  let line = '';
  for (const word of String(text).split(/\s+/).filter(Boolean)) {
    if (line && line.length + 1 + word.length > max) { lines.push(line); line = word; } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines;
};

// Rough average glyph width as a share of the font size, enough to wrap without measuring.
const charsFor = (width, size, ratio = 0.53) => Math.floor(width / (size * ratio));

/**
 * "Data: <version>" plus, for synthetic data, what made it, read from the manifest citation
 * ("... generated by tools/mock-data.mjs. ..."), so the warning is not repeated as a citation.
 */
export const dataLine = ({ dataVersion, citation, synthetic }) => {
  if (!synthetic) return `Data: ${dataVersion}`;
  const by = /generated by (\S+?)\.?(?:\s|$)/.exec(citation ?? '')?.[1];
  return `Data: ${dataVersion} (${by ? `${by}, ` : ''}not NASA FIRMS)`;
};

const periodText = (cells) => {
  if (!cells.length) return 'no months in range';
  const first = cells[0];
  const last = cells.at(-1);
  return `${monthLabel(first.year, first.month)} to ${monthLabel(last.year, last.month)}`;
};

export const synthNote = 'SYNTHETIC DEMO DATA: generated by the Prime Radiant team, not real fire detections';

/**
 * Everything drawn on the exported image, as a flat list of primitives in paint order:
 * {el: 'rect'|'text'|'path'|'line', a: attributes, text?}. Pure: no DOM, so the content is unit tested.
 * @param {{cells: object[], aoiCells: number, title: string, bbox: number[], dataVersion: string,
 *   citation: string, synthetic: boolean, generated: string}} input cells sorted by month, as on screen
 * @returns {{width: number, height: number, items: object[]}}
 */
export const imageModel = ({ cells, aoiCells, title, bbox, dataVersion, citation, synthetic, generated }) => {
  const { width: W, pad: P, label: L, cellH, rowGap, colGap, radiant: RS } = LAYOUT;
  const P_ = PALETTE;
  const items = [];
  const text = (x, y, s, a = {}) => items.push({ el: 'text', a: { x, y, fill: P_.text, 'font-size': 14, 'font-family': FONT, ...a }, text: s });
  const rect = (a) => items.push({ el: 'rect', a });
  let y = 0;

  if (synthetic) {
    rect({ x: 0, y: 0, width: W, height: 36, fill: P_.synth });
    text(P, 23, synthNote, { fill: P_.synthText, 'font-weight': 700, 'font-size': 13, 'letter-spacing': 0.3 });
    y = 36;
  }

  // Header on the left, the Radiant on the right.
  const top = y + P;
  const textW = W - 2 * P - RS - 24;
  y = top;
  text(P, y + 12, 'PRIME RADIANT · HARMONIZED MODIS AND VIIRS FIRE CALENDAR', { fill: P_.muted, 'font-size': 11.5, 'font-weight': 600, 'letter-spacing': 1 });
  y += 26;
  for (const line of wrap(title, charsFor(textW, 28, 0.58)).slice(0, 2)) {
    y += 30;
    text(P, y, line, { 'font-size': 28, 'font-weight': 700 });
  }
  y += 28;
  text(P, y, `Fire-cell-days per month, ${periodText(cells)}`, { 'font-size': 16, 'font-weight': 500 });
  for (const line of wrap(`Area: ${bboxText(bbox)}`, charsFor(textW, 13))) {
    y += 20;
    text(P, y, line, { fill: P_.muted, 'font-size': 13 });
  }

  const rad = radiantModel(cells, { aoiCells, labels: true });
  const k = RS / Number(rad.viewBox.split(' ')[2]);
  const cx = W - P - RS / 2;
  const cy = top + RS / 2;
  const at = (v) => Number(v.toFixed(2));
  items.push({ el: 'g', a: { transform: `translate(${at(cx)} ${at(cy)}) scale(${at(k * 10000) / 10000})` }, children: [
    ...rad.slices.map((s) => ({ el: 'path', a: { d: s.d, fill: P_.bins[s.bin] } })),
    ...rad.labels.map((l) => ({ el: 'text', a: { x: l.x, y: l.y, 'text-anchor': 'middle', 'dominant-baseline': 'central', fill: P_.muted, 'font-size': 7.5, 'font-weight': 500, 'font-family': FONT }, text: l.text })),
  ] });
  y = Math.max(y, top + RS) + 28;

  // The grid: newest year on top, as in the app.
  const grid = gridModel(cells, { aoiCells });
  const colW = (W - 2 * P - L - 11 * colGap) / 12;
  const colX = (c) => P + L + c * (colW + colGap);
  MONTH_ABBR.forEach((m, c) => text(at(colX(c) + colW / 2), y + 12, m, { fill: P_.muted, 'font-size': 12, 'font-weight': 500, 'text-anchor': 'middle' }));
  y += 22;
  for (const row of grid.rows) {
    text(P, y + cellH / 2 + 4.5, String(row.year), { fill: P_.muted, 'font-size': 13, 'font-weight': 500, 'font-family': MONO });
    row.cells.forEach((m, c) => {
      const x = at(colX(c));
      const box = { x, y, width: at(colW), height: cellH, rx: 4 };
      const mid = { x: at(x + colW / 2), y: y + cellH / 2 + 4, 'text-anchor': 'middle', 'font-family': MONO, 'font-size': 12, 'font-weight': 500 };
      if (!m) return;
      if (m.terraOnly) {
        rect({ ...box, fill: P_.surface2, stroke: P_.borderStrong, 'stroke-dasharray': '3 2', x: x + 0.5, y: y + 0.5, width: at(colW - 1), height: cellH - 1 });
        text(mid.x, mid.y, 'T', { ...mid, fill: P_.muted, 'font-weight': 600 });
        return;
      }
      if (m.bin === NODATA) { rect({ ...box, fill: 'url(#nodata)', 'data-kind': 'nodata' }); return; }
      const ink = P_.binText[m.bin];
      rect({ ...box, fill: P_.bins[m.bin], 'data-bin': m.bin });
      text(mid.x, mid.y, m.text, { ...mid, fill: ink });
      if (m.estimated) items.push({ el: 'path', a: { d: `M${at(x + colW - 7)} ${y}h3a4 4 0 0 1 4 4v3z`, fill: ink, 'fill-opacity': 0.55, 'data-mark': 'estimated' } });
      if (m.partial) items.push({ el: 'line', a: { x1: x + 4, x2: at(x + colW - 4), y1: y + cellH - 3, y2: y + cellH - 3, stroke: ink, 'stroke-width': 1.5, 'stroke-dasharray': '2 2', 'data-mark': 'partial' } });
    });
    y += cellH + rowGap;
  }

  // Legend: the stepped density bar, then the marks, then the unit.
  y += 20;
  const lm = legendModel();
  text(P, y, 'Density, fire-cell-days per 1,000 grid cells', { 'font-size': 13, 'font-weight': 600 });
  y += 10;
  const stepW = 58;
  BINS.forEach((b, i) => {
    rect({ x: P + i * stepW, y, width: stepW, height: 14, fill: P_.bins[b.id] });
    text(P + i * stepW + 2, y + 30, RAMP_TICKS[i], { fill: P_.muted, 'font-size': 12, 'font-family': MONO });
  });
  // Marks sit to the right of the bar, two per row.
  const mx = P + BINS.length * stepW + 40;
  const marks = [
    { id: 'nodata', label: 'No data (sensor not operating)' },
    ...lm.marks,
  ];
  marks.forEach((mk, i) => {
    const sx = mx + (i % 2) * 230;
    const sy = y - 10 + Math.floor(i / 2) * 26;
    const sw = { x: sx, y: sy, width: 18, height: 18, rx: 3 };
    if (mk.id === 'nodata') rect({ ...sw, fill: 'url(#nodata)' });
    else if (mk.id === 'terra-only') {
      rect({ ...sw, fill: P_.surface2, stroke: P_.borderStrong, 'stroke-dasharray': '3 2', x: sx + 0.5, y: sy + 0.5, width: 17, height: 17 });
      text(sx + 9, sy + 13, 'T', { fill: P_.muted, 'font-size': 10, 'font-weight': 600, 'text-anchor': 'middle', 'font-family': MONO });
    } else {
      rect({ ...sw, fill: P_.surface2, stroke: P_.border });
      if (mk.id === 'estimated') items.push({ el: 'path', a: { d: `M${sx + 11} ${sy}h4a3 3 0 0 1 3 3v4z`, fill: P_.text, 'fill-opacity': 0.55 } });
      else items.push({ el: 'line', a: { x1: sx + 3, x2: sx + 15, y1: sy + 15, y2: sy + 15, stroke: P_.text, 'stroke-width': 1.5, 'stroke-dasharray': '2 2' } });
    }
    const label = mk.id === 'terra-only' ? 'Terra only, not harmonized' : mk.label;
    text(sx + 26, sy + 13.5, label, { fill: P_.muted, 'font-size': 12.5 });
  });
  y += Math.max(44, Math.ceil(marks.length / 2) * 26 + 8);
  for (const line of wrap(lm.unit, charsFor(W - 2 * P, 12.5))) {
    y += 18;
    text(P, y, line, { fill: P_.muted, 'font-size': 12.5 });
  }

  // Provenance.
  y += 20;
  items.push({ el: 'line', a: { x1: P, x2: W - P, y1: y, y2: y, stroke: P_.border, 'stroke-width': 1 } });
  y += 22;
  text(P, y, `${dataLine({ dataVersion, citation, synthetic })} · Exported ${generated} · Unit: fire-cell-days`, { 'font-size': 12.5, 'font-weight': 500 });
  for (const line of synthetic ? [] : wrap(citation ?? '', charsFor(W - 2 * P, 12))) {
    y += 17;
    text(P, y, line, { fill: P_.muted, 'font-size': 12 });
  }
  return { width: W, height: Math.ceil(y + P), items };
};

/** PNG size in device pixels for a model. */
export const pngSize = (model) => ({ width: model.width * SCALE, height: model.height * SCALE });

const build = (item) => {
  const node = svgEl(item.el, item.a);
  if (item.text !== undefined) node.textContent = item.text;
  if (item.children) node.append(...item.children.map(build));
  return node;
};

/** The model as an <svg> element, built with DOM APIs. */
export const renderSvg = (model) => {
  const { width, height } = model;
  const svg = svgEl('svg', { xmlns: 'http://www.w3.org/2000/svg', width, height, viewBox: `0 0 ${width} ${height}` });
  const hatch = svgEl('pattern', { id: 'nodata', width: 6, height: 6, patternUnits: 'userSpaceOnUse', patternTransform: 'rotate(45)' });
  hatch.append(svgEl('rect', { width: 6, height: 6, fill: PALETTE.nodataBg }), svgEl('rect', { width: 1.2, height: 6, fill: PALETTE.nodataStripe }));
  const defs = svgEl('defs');
  defs.append(hatch);
  svg.append(defs, svgEl('rect', { width, height, fill: PALETTE.bg }), ...model.items.map(build));
  return svg;
};

/**
 * Rasterizes an <svg> to a PNG Blob through an <img> and a <canvas>. The SVG goes in as a data:
 * URL, which the CSP's img-src already allows; an SVG image loads nothing external, so the
 * canvas stays origin-clean.
 */
export const toPng = async (svg, scale = SCALE) => {
  const w = Number(svg.getAttribute('width'));
  const ht = Number(svg.getAttribute('height'));
  const img = new Image();
  img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(new XMLSerializer().serializeToString(svg))}`;
  await img.decode();
  const canvas = document.createElement('canvas');
  canvas.width = w * scale;
  canvas.height = ht * scale;
  const ctx = canvas.getContext('2d');
  ctx.scale(scale, scale);
  ctx.drawImage(img, 0, 0, w, ht);
  return new Promise((resolve, reject) => canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('the browser could not encode the PNG'))), 'image/png'));
};
