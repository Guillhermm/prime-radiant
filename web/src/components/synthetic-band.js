import { isSyntheticManifest } from '../view-data.js';
import { h } from './h.js';

export const TITLE_PREFIX = 'Synthetic data: ';

/** Band copy while the data version starts with "synthetic"; null for real data. */
export const syntheticModel = (manifest) => (isSyntheticManifest(manifest) ? {
  label: 'Synthetic demo data',
  sentence: 'Generated by the team to show how the app works. These are not real fire detections.',
  short: 'Not real fire detections.',
  link: 'About',
} : null);

export const titleFor = (title, synthetic) => (synthetic ? `${TITLE_PREFIX}${title}` : title);

/**
 * mount(container, {manifest, onAbout(trigger)}). Renders the band (role note, not dismissible)
 * and a fixed decorative frame around the window, so any screenshot still says synthetic.
 */
export const mount = (container, { manifest, onAbout }) => {
  const m = syntheticModel(manifest);
  if (!m) { container.replaceChildren(); return { synthetic: false }; }
  container.replaceChildren(
    h('div', { class: 'synth-frame', 'aria-hidden': 'true' }),
    h('div', { class: 'synth-band', role: 'note' },
      h('span', { class: 'stripes', 'aria-hidden': 'true' }),
      h('strong', { text: m.label }),
      h('span', { class: 'synth-long', text: m.sentence }),
      h('span', { class: 'synth-short', text: m.short }),
      h('button', { type: 'button', class: 'synth-about', text: m.link, onclick: (ev) => onAbout?.(ev.currentTarget) })));
  return { synthetic: true };
};
