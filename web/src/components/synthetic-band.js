import { isSyntheticManifest } from '../view-data.js';
import { h } from './h.js';
import { icon } from './icons.js';
import { popover, restoreFocus } from './popover.js';

export const TITLE_PREFIX = 'Synthetic data: ';

/** Band copy while the data version starts with "synthetic"; null for real data. */
export const syntheticModel = (manifest) => (isSyntheticManifest(manifest) ? {
  label: 'Synthetic demo data',
  sentence: 'Generated by the team to show how the app works. These are not real fire detections.',
  short: 'Not real fire detections.',
  link: 'What is this?',
  tag: 'Synthetic data',
  tagShort: 'Synthetic',
  tagRest: ' data',
  close: 'Hide the synthetic data notice',
  about: {
    title: 'Synthetic demo data',
    what: 'Every fire count on screen comes from a generator the team wrote: random fires over South America and California, with a fire season and some busier and quieter years.',
    why: 'It lets the app be shown and tested before the real NASA FIRMS record is loaded.',
    not: 'These are not real fire detections. Do not use them for any decision.',
    more: 'How the method works',
  },
} : null);

export const titleFor = (title, synthetic) => (synthetic ? `${TITLE_PREFIX}${title}` : title);

export const DISMISS_KEY = 'pr-synth-banner-closed';

// Even reading the sessionStorage property can throw (blocked site data), so it is looked up inside
// the try; on failure the banner simply shows again.
const session = (storage) => storage ?? globalThis.sessionStorage;
export const bannerClosed = (storage) => {
  try { return session(storage)?.getItem(DISMISS_KEY) === '1'; } catch { return false; }
};
export const rememberClosed = (storage) => {
  try { session(storage)?.setItem(DISMISS_KEY, '1'); } catch { /* banner returns on reload */ }
};

const reducedMotion = () => globalThis.matchMedia?.('(prefers-reduced-motion: reduce)').matches;

/**
 * Takes the band out of the flow in one layout, then slides it up and out (transform and
 * opacity) while the content below, already in its final place, starts shifted down by the
 * band's height and glides up: a FLIP, so no frame recomputes layout.
 */
const collapse = (band, below, done) => {
  const height = band.offsetHeight;
  if (reducedMotion() || typeof band.animate !== 'function' || height === 0) { done(); return; }
  band.classList.add('is-leaving');
  const opts = { duration: 220, easing: 'cubic-bezier(0.2, 0, 0, 1)' };
  const out = band.animate([{ transform: 'none', opacity: 1 }, { transform: 'translateY(-100%)', opacity: 0 }], opts);
  below.forEach((el) => el.animate([{ transform: `translateY(${height}px)` }, { transform: 'none' }], opts));
  out.finished.then(done, done);
};

/**
 * mount(container, {manifest, tagSlot, below, onMethod(trigger)}). Renders the closable band
 * (role note), the "Synthetic data" tag that stays in the top bar once the band is closed, and
 * the About popover (see popover.js for browsers without the Popover API) that both
 * open, whose one link opens the Method drawer. `below` lists the elements that slide up when
 * the band collapses.
 */
export const mount = (container, { manifest, tagSlot, below = [], onMethod, storage }) => {
  const m = syntheticModel(manifest);
  if (!m) { container.replaceChildren(); tagSlot?.replaceChildren(); return { synthetic: false }; }
  const a = m.about;
  const about = h('button', { type: 'button', class: 'synth-about', text: m.link, popovertarget: 'synth-about', 'aria-haspopup': 'dialog' });
  const tag = h('button', { type: 'button', class: 'synth-tag', popovertarget: 'synth-about', 'aria-haspopup': 'dialog', 'aria-label': m.tag },
    h('span', { class: 'stripes', 'aria-hidden': 'true' }), h('span', { text: m.tagShort }), h('span', { class: 'synth-tag-rest', text: m.tagRest }));
  const close = h('button', { type: 'button', class: 'synth-close', 'aria-label': m.close }, icon('close'));
  const more = h('button', { type: 'button', class: 'synth-more', text: a.more });
  const pop = h('div', { id: 'synth-about', class: 'synth-pop', popover: 'auto', role: 'dialog', 'aria-labelledby': 'synth-about-title' },
    h('h2', { id: 'synth-about-title', class: 'synth-pop-title', text: a.title }),
    h('p', { text: a.what }), h('p', { text: a.why }), h('p', { class: 'synth-pop-not', text: a.not }), more);
  // Place the popover under whichever button opened it. A fixed popover would float away from
  // its button on scroll, so scrolling closes it; on close focus returns to that button.
  let opener = about;
  const ctl = popover(pop, [about, tag], {
    onOpen: (btn) => {
      opener = btn;
      const r = btn.getBoundingClientRect();
      pop.dataset.anchor = btn === tag ? 'start' : 'end';
      pop.style.setProperty('--pop-top', `${Math.round(r.bottom + 6)}px`);
      pop.style.setProperty('--pop-start', `${Math.round(r.left)}px`);
    },
    onClose: (btn) => restoreFocus(pop, btn),
    closeOnScroll: true,
  });
  more.addEventListener('click', () => { ctl.hide(); onMethod?.(opener); });
  const band = h('div', { class: 'synth-band', role: 'note' },
    h('span', { class: 'stripes', 'aria-hidden': 'true' }),
    h('strong', { text: m.label }),
    h('span', { class: 'synth-long', text: m.sentence }),
    h('span', { class: 'synth-short', text: m.short }),
    about, close);
  const closed = bannerClosed(storage);
  band.hidden = closed;
  tag.hidden = !closed;
  close.addEventListener('click', () => {
    rememberClosed(storage);
    tag.hidden = false;
    tag.focus();
    collapse(band, below, () => { band.hidden = true; band.classList.remove('is-leaving'); });
  });
  container.replaceChildren(band, pop);
  tagSlot?.replaceChildren(tag);
  return { synthetic: true };
};
