import { test } from 'node:test';
import assert from 'node:assert/strict';
import { colorOf, loadThemes } from '../../../tools/contrast.mjs';
import { PALETTE, SCALE, dataLine, imageModel, pngSize, synthNote, wrap } from './export-image.js';
import { imageExport } from './export-menu.js';

const cell = (year, month, value, extra = {}) => ({ year, month, value, status: 'observed', estimated: false, flags: [], ...extra });
const cells = [
  cell(2002, 6, null, { flags: ['terra-only'] }),
  cell(2002, 7, 0),
  cell(2002, 8, 5, { estimated: true, status: 'harmonized' }),
  cell(2002, 9, null),
  cell(2003, 1, 2500),
  cell(2003, 2, 40, { status: 'partial' }),
];
const input = {
  cells, aoiCells: 100, title: 'Pantanal', bbox: [-58.2, -20.1, -55, -15.3], dataVersion: 'v2026-11',
  citation: 'NASA FIRMS MODIS and VIIRS active fire archive.', synthetic: false, generated: '2026-11-15',
};
const texts = (m) => m.items.filter((i) => i.el === 'text').map((i) => i.text);
const fills = (m) => m.items.filter((i) => i.el === 'rect' && i.a['data-bin'] !== undefined);

test('the export palette is the light theme of tokens.css', () => {
  const { light } = loadThemes();
  const c = (n) => colorOf(light, n, '#ffffff');
  assert.deepEqual(PALETTE.bins, [0, 1, 2, 3, 4, 5, 6].map((i) => c(`bin-${i}`)));
  assert.deepEqual(PALETTE.binText, [0, 1, 2, 3, 4, 5, 6].map((i) => c(`bin-${i}-text`)));
  assert.equal(PALETTE.bg, c('color-surface'));
  assert.equal(PALETTE.text, c('color-text'));
  assert.equal(PALETTE.muted, c('color-text-muted'));
  assert.equal(PALETTE.border, c('color-border'));
  assert.equal(PALETTE.borderStrong, c('color-border-strong'));
  assert.equal(PALETTE.surface2, c('color-surface-2'));
  assert.equal(PALETTE.nodataBg, c('nodata-bg'));
  assert.equal(PALETTE.nodataStripe, c('nodata-stripe'));
  assert.equal(PALETTE.synth, c('color-synth'));
});

test('wrap breaks at spaces within the limit', () => {
  assert.deepEqual(wrap('one two three four', 9), ['one two', 'three', 'four']);
  assert.deepEqual(wrap('', 9), []);
  assert.deepEqual(wrap('averyveryverylongword x', 5), ['averyveryverylongword', 'x']);
});

test('title, period, area, unit, data version and citation are on the image', () => {
  const t = texts(imageModel(input)).join('\n');
  assert.match(t, /^Pantanal$/m);
  assert.match(t, /Fire-cell-days per month, June 2002 to February 2003/);
  assert.match(t, /Area: 20\.1°S–15\.3°S · 58\.2°W–55°W/, 'the chip\'s bbox format');
  assert.match(t, /fire-cell-days per 1,000 grid cells/);
  assert.match(t, /Data: v2026-11 · Exported 2026-11-15 · Unit: fire-cell-days/);
  assert.match(t, /NASA FIRMS MODIS and VIIRS active fire archive\./);
  assert.ok(!t.includes(synthNote), 'real data carries no synthetic notice');
});

test('synthetic data carries the notice once, in the top band; the data line names the generator', () => {
  const citation = 'SYNTHETIC DEMO DATA generated by tools/mock-data.mjs. Not real detections, not NASA FIRMS.';
  const m = imageModel({ ...input, synthetic: true, dataVersion: 'synthetic-20261115', citation });
  assert.equal(texts(m).filter((s) => s === synthNote).length, 1);
  assert.ok(m.items.some((i) => i.el === 'rect' && i.a.fill === PALETTE.synth && i.a.y === 0));
  assert.ok(texts(m).some((s) => s.startsWith('Data: synthetic-20261115 (tools/mock-data.mjs, not NASA FIRMS) · Exported')));
  assert.ok(!texts(m).includes(citation), 'the synthetic citation is not repeated');
  assert.equal(dataLine({ dataVersion: 'v1', citation, synthetic: false }), 'Data: v1');
  assert.equal(dataLine({ dataVersion: 's', citation: '', synthetic: true }), 'Data: s (not NASA FIRMS)');
});

test('cells: zero is class 0, no data is hatched, Terra only is lettered, marks for estimated and partial', () => {
  const m = imageModel(input);
  const binned = fills(m);
  assert.deepEqual(binned.map((r) => r.a['data-bin']), [6, 5, 0, 3], 'newest year first, left to right');
  assert.equal(binned[2].a.fill, PALETTE.bins[0], 'a zero month is colored as zero detections');
  const nodata = m.items.filter((i) => i.a['data-kind'] === 'nodata');
  assert.equal(nodata.length, 1, 'the null month is no data, not zero');
  assert.equal(nodata[0].a.fill, 'url(#nodata)');
  assert.ok(texts(m).includes('T'), 'Terra-only month is lettered');
  assert.equal(m.items.filter((i) => i.a['data-mark'] === 'estimated').length, 1);
  assert.equal(m.items.filter((i) => i.a['data-mark'] === 'partial').length, 1);
  assert.ok(texts(m).includes('2.5k'), 'cells print the abbreviated raw count');
  assert.ok(texts(m).includes('No data (sensor not operating)'));
});

test('the Radiant draws one slice per month with a value, ring and letters legible at 2x', () => {
  const g = imageModel(input).items.find((i) => i.el === 'g');
  assert.equal(g.children.filter((c) => c.el === 'path').length, 4);
  const k = Number(/scale\(([\d.]+)\)/.exec(g.a.transform)[1]);
  assert.ok(96 * 2 * k * SCALE >= 360, 'ring at least 360 px across in the PNG');
  const letter = g.children.find((c) => c.el === 'text');
  assert.ok(letter.a['font-size'] * k * SCALE >= 11, 'month letters at least 11 px in the PNG');
});

test('months outside the period draw nothing', () => {
  const m = imageModel({ ...input, cells: [cell(2003, 3, 5)] });
  assert.equal(m.items.filter((i) => i.el === 'rect' && i.a.fill === 'none').length, 0, 'no empty boxes');
  assert.equal(m.items.filter((i) => i.el === 'rect' && i.a['data-bin'] !== undefined).length, 1);
});

test('size: fixed width, height grows with the years, PNG at twice the size', () => {
  const one = imageModel({ ...input, cells: cells.filter((c) => c.year === 2003) });
  const two = imageModel(input);
  assert.equal(one.width, 1000);
  assert.equal(two.height - one.height, 28, 'one more year adds one row');
  assert.deepEqual(pngSize(two), { width: 2000, height: two.height * 2 });
});

test('imageExport names the file like the CSV, with .png', async () => {
  const blob = new Blob(['x']);
  const out = await imageExport({ ...input, series: { start: '2002-06', values: new Array(9).fill(0) }, manifest: { dataVersion: 'v', citation: 'c' } }, { rasterize: async () => blob });
  assert.equal(out.filename, 'prime-radiant-2002-06-2003-02.png');
  assert.equal(out.mime, 'image/png');
  assert.equal(out.blob, blob);
});
