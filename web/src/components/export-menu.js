import { toCsv } from '../../../core/index.js';
import { h } from './h.js';
import { icon } from './icons.js';

const addMonths = (ym, n) => {
  const i = Number(ym.slice(0, 4)) * 12 + Number(ym.slice(5, 7)) - 1 + n;
  return `${Math.floor(i / 12)}-${String((i % 12) + 1).padStart(2, '0')}`;
};

/** "prime-radiant-2001-01-2026-10.csv": the first and last month of the exported series. */
export const exportFilename = (series, { prefix = 'prime-radiant', ext = 'csv' } = {}) => {
  const last = addMonths(series.start, Math.max(0, series.values.length - 1));
  return `${prefix}-${series.start}-${last}.${ext}`;
};

const FORMULA_START = /^[=+\-@\t\r]/;
const NUMBER = /^-?\d+(\.\d+)?$/;
const guardField = (f) => (FORMULA_START.test(f.trimStart()) && !NUMBER.test(f.trim()) ? `'${f}` : f);

/**
 * Temporary web-side guard against CSV formula injection (OWASP): every comma-separated field that
 * starts with = + - @ tab or CR gets a leading apostrophe, and so does a header value after "# key: ".
 * Bare numbers, negative ones included, are left alone. Remove when core/csv.js guards its own
 * output (docs/deploy.md).
 */
export const guardCsv = (text) => text.split('\n').map((line) => {
  const [first, ...rest] = line.split(',');
  const i = line.startsWith('# ') ? first.indexOf(': ') : -1;
  const head = i < 0 ? guardField(first) : `${first.slice(0, i + 2)}${guardField(first.slice(i + 2))}`;
  return [head, ...rest.map(guardField)].join(',');
}).join('\n');

/** The CSV file for a series: text is `core.toCsv(series, meta)` passed through guardCsv. */
export const csvExport = (series, meta) => ({
  filename: exportFilename(series),
  mime: 'text/csv;charset=utf-8',
  text: guardCsv(toCsv(series, meta)),
});

export const SYNTHETIC_LINE = '# SYNTHETIC DEMO DATA: generated by the Prime Radiant team, not real fire detections';

/** Puts the synthetic warning on the first line of the file when the data is synthetic. */
export const withSyntheticNote = (text, synthetic) => (synthetic ? `${SYNTHETIC_LINE}\n${text}` : text);

export const savedMessage = (filename) => `CSV saved: ${filename}`;

export const TOAST_MS = 4000;

const browserDownload = ({ filename, mime, text }) => {
  const url = URL.createObjectURL(new Blob([text], { type: mime }));
  const a = h('a', { href: url, download: filename });
  document.body.append(a);
  a.click();
  a.remove();
  // Safari can start the download after click() returns; revoking at once cancels it.
  setTimeout(() => URL.revokeObjectURL(url), 10000);
};

/**
 * mount(container, deps). One primary button that downloads the CSV of what is on screen.
 * deps: `getSeries()` returns the Series or null, `getMeta()` extra CSV header lines,
 * `isSynthetic()`; optional `download(file)` for tests. A toast (role status) reports
 * the result for four seconds. Returns {destroy()}.
 */
export const mount = (container, deps) => {
  const download = deps.download ?? browserDownload;
  const button = h('button', { type: 'button', class: 'btn btn-primary export-button', 'aria-label': 'Export CSV' },
    icon('download'), h('span', { class: 'btn-label', text: 'Export CSV' }));
  const status = h('p', { class: 'toast export-status', role: 'status' });
  container.replaceChildren(button, status);
  let timer = 0;
  const say = (msg) => {
    status.textContent = msg;
    clearTimeout(timer);
    timer = setTimeout(() => { status.textContent = ''; }, TOAST_MS);
  };
  button.addEventListener('click', () => {
    try {
      const series = deps.getSeries();
      if (!series) return say('Nothing to export yet. Choose an area first.');
      const file = csvExport(series, deps.getMeta?.() ?? {});
      file.text = withSyntheticNote(file.text, deps.isSynthetic?.() ?? false);
      download(file);
      return say(savedMessage(file.filename));
    } catch (err) {
      return say(`Export failed: ${err.message}`);
    }
  });
  return { destroy: () => { clearTimeout(timer); container.replaceChildren(); } };
};
